//! Audio, DSP, Equalizer, and Hotplug Recovery domain subsystem.

use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Mutex;
use std::time::Instant;

use crate::equalizer::{AudioDeviceInfo, EqualizerManager, EqualizerSettings};
use crate::error::MpvError;
use crate::handle::MpvHandle;
use crate::settings::AudioChannelsSetting;

/// Status and telemetry for dynamic range compression and audio normalization.
#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct DynamicsTelemetry {
    /// Whether dynamic normalization (`dynaudnorm`) is active in the filter pipeline.
    pub normalization_active: bool,
    /// Measured gain reduction in dB if exported by the filter backend, or None if unexported.
    pub gain_reduction_db: Option<f64>,
    /// Informational telemetry message regarding DSP status.
    pub status_message: String,
}

/// Recovery state of the audio output subsystem.
#[derive(Debug, Clone, PartialEq, Default)]
pub enum AudioRecoveryStatus {
    #[default]
    Normal,
    DeviceLost {
        device_name: String,
        fallback_device: String,
    },
    Recovered {
        active_device: String,
        was_device: String,
    },
    Degraded {
        reason: String,
    },
}

/// Event generated by audio hotplug and device state changes.
#[derive(Debug, Clone, PartialEq)]
pub enum AudioDeviceChangeEvent {
    DeviceListUpdated {
        count: usize,
    },
    DeviceDisconnected {
        lost: String,
        fallback: String,
    },
    PreferredDeviceReconnected {
        device: String,
    },
    SinkFailed {
        previous_ao: String,
        fallback_ao: String,
    },
}

struct AudioHotplugState {
    preferred_device: String,
    active_device: String,
    known_devices: Vec<AudioDeviceInfo>,
    recovery_status: AudioRecoveryStatus,
    retry_count: u32,
    last_retry_instant: Option<Instant>,
    pending_notifications: Vec<String>,
}

/// Subsystem managing volume, pitch, equalizers, audio routing, and hotplug recovery.
pub struct AudioSubsystem {
    volume: f64,
    volume_boost_max: f64,
    is_muted: bool,
    speed: f64,
    audio_delay: f64,
    current_ao: String,
    audio_codec: String,
    pitch_correction: bool,
    gapless_audio: AtomicBool,
    hotplug: Mutex<AudioHotplugState>,
}

impl Default for AudioSubsystem {
    fn default() -> Self {
        Self::new()
    }
}

impl AudioSubsystem {
    /// Creates a new `AudioSubsystem` with engine defaults.
    pub fn new() -> Self {
        Self {
            volume: 100.0,
            volume_boost_max: 100.0,
            is_muted: false,
            speed: 1.0,
            audio_delay: 0.0,
            current_ao: "none".to_string(),
            audio_codec: String::new(),
            pitch_correction: true,
            gapless_audio: AtomicBool::new(true),
            hotplug: Mutex::new(AudioHotplugState {
                preferred_device: "auto".to_string(),
                active_device: "auto".to_string(),
                known_devices: Vec::new(),
                recovery_status: AudioRecoveryStatus::Normal,
                retry_count: 0,
                last_retry_instant: None,
                pending_notifications: Vec::new(),
            }),
        }
    }

    /// Returns the current playback volume (0.0 to 150.0).
    pub fn volume(&self) -> f64 {
        self.volume
    }

    /// Sets the playback volume, clamped to `[0.0, volume_boost_max]`.
    pub fn set_volume(&mut self, handle: &MpvHandle, volume: f64) -> Result<(), MpvError> {
        let clamped = volume.clamp(0.0, self.volume_boost_max);
        handle.set_property("volume", clamped)?;
        self.volume = clamped;
        Ok(())
    }

    /// Adjusts the volume by `delta` percent points.
    pub fn adjust_volume(&mut self, handle: &MpvHandle, delta: f64) -> Result<(), MpvError> {
        self.set_volume(handle, self.volume + delta)
    }

    /// Sets the maximum allowable volume including software boost (up to 150%).
    pub fn set_volume_boost(
        &mut self,
        handle: &MpvHandle,
        boost_percent: f64,
    ) -> Result<(), MpvError> {
        let max_vol = boost_percent.clamp(100.0, 150.0);
        self.volume_boost_max = max_vol;
        handle.set_property("volume-max", max_vol)?;
        if self.volume > self.volume_boost_max {
            self.volume = self.volume_boost_max;
        }
        Ok(())
    }

    /// Returns the current maximum volume boost ceiling (100.0 to 150.0).
    pub fn volume_boost_max(&self) -> f64 {
        self.volume_boost_max
    }

    /// Returns whether audio is currently muted.
    pub fn is_muted(&self) -> bool {
        self.is_muted
    }

    /// Sets the mute state.
    pub fn set_mute(&mut self, handle: &MpvHandle, muted: bool) -> Result<(), MpvError> {
        handle.set_property("mute", muted)?;
        self.is_muted = muted;
        Ok(())
    }

    /// Toggles the mute state.
    pub fn toggle_mute(&mut self, handle: &MpvHandle) -> Result<(), MpvError> {
        self.set_mute(handle, !self.is_muted)
    }

    /// Returns the current playback speed multiplier.
    pub fn speed(&self) -> f64 {
        self.speed
    }

    /// Sets playback speed multiplier in range `[0.25, 4.0]`.
    pub fn set_speed(&mut self, handle: &MpvHandle, speed: f64) -> Result<(), MpvError> {
        let clamped = speed.clamp(0.25, 4.0);
        handle.set_property("speed", clamped)?;
        self.speed = clamped;
        Ok(())
    }

    /// Adjusts playback speed by `delta`.
    pub fn adjust_speed(&mut self, handle: &MpvHandle, delta: f64) -> Result<(), MpvError> {
        self.set_speed(handle, self.speed + delta)
    }

    /// Resets playback speed to 1.0x.
    pub fn reset_speed(&mut self, handle: &MpvHandle) -> Result<(), MpvError> {
        self.set_speed(handle, 1.0)
    }

    /// Sets the audio track delay in seconds.
    pub fn set_audio_delay(
        &mut self,
        handle: &MpvHandle,
        delay_seconds: f64,
    ) -> Result<(), MpvError> {
        handle.set_property("audio-delay", delay_seconds)?;
        self.audio_delay = delay_seconds;
        Ok(())
    }

    /// Returns the current audio delay in seconds.
    pub fn audio_delay(&self, handle: &MpvHandle) -> Result<f64, MpvError> {
        handle.get_property::<f64>("audio-delay")
    }

    /// Enables or disables time-stretch pitch correction.
    pub fn set_pitch_correction(
        &mut self,
        handle: &MpvHandle,
        enabled: bool,
    ) -> Result<(), MpvError> {
        let val = if enabled { "yes" } else { "no" };
        handle.set_property_string("audio-pitch-correction", val)?;
        self.pitch_correction = enabled;
        Ok(())
    }

    /// Configures audio channel layout (`stereo`, `5.1`, `7.1`, or `auto`).
    pub fn set_channel_layout(&self, handle: &MpvHandle, layout: &str) -> Result<(), MpvError> {
        let target = match layout.to_lowercase().as_str() {
            "stereo" => "stereo",
            "5.1" | "surround51" => "5.1",
            "7.1" | "surround71" => "7.1",
            _ => "auto",
        };
        handle.set_property_string("audio-channels", target)
    }

    /// Applies high-level `AudioChannelsSetting`.
    pub fn set_audio_channels(
        &self,
        handle: &MpvHandle,
        channels: AudioChannelsSetting,
    ) -> Result<(), MpvError> {
        let val = match channels {
            AudioChannelsSetting::Auto => "auto",
            AudioChannelsSetting::AutoSafe => "auto-safe",
            AudioChannelsSetting::Mono => "mono",
            AudioChannelsSetting::Stereo => "stereo",
            AudioChannelsSetting::ReverseStereo => "reverse-stereo",
        };
        handle.set_property_string("audio-channels", val)
    }

    /// Sets preferred audio languages (e.g. "eng,jpn").
    pub fn set_audio_languages(&self, handle: &MpvHandle, languages: &str) -> Result<(), MpvError> {
        handle.set_property_string("alang", languages)
    }

    /// Returns the currently active audio output driver name.
    pub fn current_ao(&self) -> &str {
        &self.current_ao
    }

    /// Returns the detected audio codec name.
    pub fn audio_codec(&self) -> &str {
        &self.audio_codec
    }

    /// Returns the user's preferred audio device.
    pub fn preferred_device(&self) -> String {
        self.hotplug.lock().unwrap().preferred_device.clone()
    }

    /// Returns the currently active audio device.
    pub fn active_device(&self) -> String {
        self.hotplug.lock().unwrap().active_device.clone()
    }

    /// Returns the recovery status of the audio subsystem.
    pub fn recovery_status(&self) -> AudioRecoveryStatus {
        self.hotplug.lock().unwrap().recovery_status.clone()
    }

    /// Queries detected audio output devices.
    pub fn audio_devices(&self, handle: &MpvHandle) -> Result<Vec<AudioDeviceInfo>, MpvError> {
        EqualizerManager::query_audio_devices(handle)
    }

    /// Selects an audio output device by name.
    pub fn set_audio_device(&self, handle: &MpvHandle, device_name: &str) -> Result<(), MpvError> {
        EqualizerManager::set_audio_device(handle, device_name)?;
        let mut state = self.hotplug.lock().unwrap();
        state.preferred_device = device_name.to_string();
        state.active_device = device_name.to_string();
        state.recovery_status = AudioRecoveryStatus::Normal;
        state.retry_count = 0;
        if !state.known_devices.iter().any(|d| d.name == device_name) {
            state.known_devices.push(AudioDeviceInfo {
                name: device_name.to_string(),
                description: device_name.to_string(),
            });
        }
        Ok(())
    }

    /// Selects an audio output device with automatic fallback to "auto".
    pub fn set_audio_device_with_fallback(
        &self,
        handle: &MpvHandle,
        preferred_device: &str,
    ) -> Result<String, MpvError> {
        let chosen = EqualizerManager::set_audio_device_with_fallback(handle, preferred_device)?;
        let mut state = self.hotplug.lock().unwrap();
        state.preferred_device = preferred_device.to_string();
        state.active_device = chosen.clone();
        state.recovery_status = AudioRecoveryStatus::Normal;
        state.retry_count = 0;
        Ok(chosen)
    }

    /// Applies 10-band equalizer and crossfeed settings.
    pub fn apply_equalizer(
        &self,
        handle: &MpvHandle,
        settings: &EqualizerSettings,
    ) -> Result<(), MpvError> {
        EqualizerManager::apply_to_handle(handle, settings)
    }

    /// Resets all audio filters and equalizer settings.
    pub fn reset_equalizer(&self, handle: &MpvHandle) -> Result<(), MpvError> {
        EqualizerManager::reset(handle)
    }

    /// Queries dynamic normalization and dynamic range compression telemetry.
    pub fn dynamics_telemetry(
        &self,
        handle: &MpvHandle,
        is_normalization_enabled: bool,
    ) -> DynamicsTelemetry {
        if !is_normalization_enabled {
            return DynamicsTelemetry {
                normalization_active: false,
                gain_reduction_db: None,
                status_message: "Dynamic normalization inactive (Bypassed)".to_string(),
            };
        }

        // Allow test probe injection for calibration and automated verification
        if let Ok(test_val) = std::env::var("MUVRIX_DYNAMICS_GR_TEST") {
            if let Ok(val) = test_val.parse::<f64>() {
                return DynamicsTelemetry {
                    normalization_active: true,
                    gain_reduction_db: Some(val),
                    status_message: format!("Active: {:.1} dB gain reduction", val),
                };
            }
        }

        // Query af-metadata for gain reduction if published by the filter backend
        let gr = handle
            .get_property_string("af-metadata/dynaudnorm/gain_reduction")
            .or_else(|_| handle.get_property_string("af-metadata/acompressor/gain_reduction"))
            .ok()
            .and_then(|s| s.parse::<f64>().ok());

        DynamicsTelemetry {
            normalization_active: true,
            gain_reduction_db: gr,
            status_message: if let Some(val) = gr {
                format!("Active: {:.1} dB gain reduction", val)
            } else {
                "Active (FFmpeg Dynamic Audio Normalizer engaged)".to_string()
            },
        }
    }

    /// Queries real-time audio spectrum telemetry from libmpv's active passthrough filter chain.
    pub fn spectrum_telemetry(
        &self,
        handle: &MpvHandle,
        is_playing: bool,
        is_paused: bool,
    ) -> crate::spectrum::SpectrumTelemetry {
        use crate::spectrum::SpectrumTelemetry;

        if !is_playing {
            return SpectrumTelemetry {
                is_playing: false,
                is_paused,
                ..SpectrumTelemetry::default()
            };
        }

        // Allow test probe injection for automated testing and deterministic validation
        if let Ok(test_val) = std::env::var("MUVRIX_SPECTRUM_TEST_TELEMETRY") {
            if let Ok(parsed) = serde_json::from_str::<SpectrumTelemetry>(&test_val) {
                return parsed;
            }
        }

        // Query RMS level and peak level from @vis (astats)
        let rms_db = handle
            .get_property_string("af-metadata/vis/lavfi.astats.Overall.RMS_level")
            .ok()
            .and_then(|s| s.parse::<f64>().ok())
            .unwrap_or(-100.0);

        let peak_db = handle
            .get_property_string("af-metadata/vis/lavfi.astats.Overall.Peak_level")
            .ok()
            .and_then(|s| s.parse::<f64>().ok())
            .unwrap_or(-100.0);

        // Query spectral features from @spec (aspectralstats)
        let centroid = handle
            .get_property_string("af-metadata/spec/lavfi.aspectralstats.1.centroid")
            .ok()
            .and_then(|s| s.parse::<f64>().ok())
            .unwrap_or(1000.0);

        let spread = handle
            .get_property_string("af-metadata/spec/lavfi.aspectralstats.1.spread")
            .ok()
            .and_then(|s| s.parse::<f64>().ok())
            .unwrap_or(400.0);

        let rolloff = handle
            .get_property_string("af-metadata/spec/lavfi.aspectralstats.1.rolloff")
            .ok()
            .and_then(|s| s.parse::<f64>().ok())
            .unwrap_or(8000.0);

        let flatness = handle
            .get_property_string("af-metadata/spec/lavfi.aspectralstats.1.flatness")
            .ok()
            .and_then(|s| s.parse::<f64>().ok())
            .unwrap_or(0.1);

        let slope = handle
            .get_property_string("af-metadata/spec/lavfi.aspectralstats.1.slope")
            .ok()
            .and_then(|s| s.parse::<f64>().ok())
            .unwrap_or(0.0);

        SpectrumTelemetry {
            rms_db,
            peak_db,
            spectral_centroid: centroid,
            spectral_spread: spread,
            spectral_rolloff: rolloff,
            spectral_flatness: flatness,
            spectral_slope: slope,
            is_playing: true,
            is_paused,
        }
    }

    /// Returns whether gapless audio mode is currently enabled.
    pub fn gapless_audio(&self) -> bool {
        self.gapless_audio.load(Ordering::Relaxed)
    }

    /// Configures gapless audio playback mode (`yes`, `no`, or `weak`).
    pub fn set_gapless_audio(&self, handle: &MpvHandle, mode: &str) -> Result<(), MpvError> {
        let val = match mode.to_lowercase().as_str() {
            "yes" | "true" => "yes",
            "weak" => "weak",
            _ => "no",
        };
        handle.set_property_string("gapless-audio", val)?;
        self.gapless_audio.store(val != "no", Ordering::Relaxed);
        Ok(())
    }

    /// Pre-fetches the next audio track in playlist to guarantee seamless gapless playback.
    pub fn prefetch_next_track(&self, handle: &MpvHandle) {
        if let Ok(pos) = handle.get_property::<i64>("playlist-pos") {
            if let Ok(count) = handle.get_property::<i64>("playlist-count") {
                if pos + 1 < count {
                    log::debug!("Prefetching playlist track {} for gapless audio", pos + 1);
                    let _ =
                        handle.command(&["playlist-play-index", &(pos + 1).to_string(), "pause"]);
                }
            }
        }
    }

    // -------------------------------------------------------------------------
    // Audio Hotplug Recovery & Sink Watchdog Implementation
    // -------------------------------------------------------------------------

    /// Handles changes in the detected audio output devices (`audio-device-list`).
    pub fn on_device_list_changed(&self, handle: &MpvHandle) -> Option<AudioDeviceChangeEvent> {
        let current_devices = match EqualizerManager::query_audio_devices(handle) {
            Ok(devs) => devs,
            Err(e) => {
                log::warn!("Failed to query audio devices during hotplug event: {e}");
                return None;
            }
        };
        self.handle_device_inventory_change(handle, current_devices)
    }

    /// Processes an updated list of audio output devices, detecting disconnections and reconnections.
    pub fn handle_device_inventory_change(
        &self,
        handle: &MpvHandle,
        current_devices: Vec<AudioDeviceInfo>,
    ) -> Option<AudioDeviceChangeEvent> {
        let mut state = self.hotplug.lock().unwrap();
        let old_devices = std::mem::replace(&mut state.known_devices, current_devices.clone());
        let mut event = None;

        // Check if preferred device was disconnected
        if state.preferred_device != "auto" && !state.preferred_device.is_empty() {
            let was_present = old_devices.iter().any(|d| d.name == state.preferred_device);
            let is_present = current_devices
                .iter()
                .any(|d| d.name == state.preferred_device);

            if was_present && !is_present {
                log::warn!(
                    "Audio output device '{}' was disconnected; initiating graceful fallback to 'auto'",
                    state.preferred_device
                );

                if let Err(e) = EqualizerManager::set_audio_device(handle, "auto") {
                    log::error!("Failed to route audio to 'auto' upon device disconnect: {e}");
                }
                let _ = handle.command(&["ao-reload"]);

                state.active_device = "auto".to_string();
                state.recovery_status = AudioRecoveryStatus::DeviceLost {
                    device_name: state.preferred_device.clone(),
                    fallback_device: "auto".to_string(),
                };

                let note = format!(
                    "Audio device '{}' disconnected; rerouted to system default",
                    state.preferred_device
                );
                state.pending_notifications.push(note);

                event = Some(AudioDeviceChangeEvent::DeviceDisconnected {
                    lost: state.preferred_device.clone(),
                    fallback: "auto".to_string(),
                });
            } else if !was_present && is_present {
                log::info!(
                    "Preferred audio output device '{}' reconnected; restoring route",
                    state.preferred_device
                );

                if let Err(e) = EqualizerManager::set_audio_device(handle, &state.preferred_device)
                {
                    log::warn!("Failed to restore preferred device: {e}");
                }
                let _ = handle.command(&["ao-reload"]);

                let was_dev = state.active_device.clone();
                state.active_device = state.preferred_device.clone();
                state.recovery_status = AudioRecoveryStatus::Recovered {
                    active_device: state.preferred_device.clone(),
                    was_device: was_dev,
                };

                let note = format!(
                    "Preferred audio device '{}' reconnected; restored route",
                    state.preferred_device
                );
                state.pending_notifications.push(note);

                event = Some(AudioDeviceChangeEvent::PreferredDeviceReconnected {
                    device: state.preferred_device.clone(),
                });
            }
        }

        if event.is_none() {
            Some(AudioDeviceChangeEvent::DeviceListUpdated {
                count: current_devices.len(),
            })
        } else {
            event
        }
    }

    /// Handles changes in the active audio output driver (`current-ao`).
    pub fn on_current_ao_changed(
        &mut self,
        handle: &MpvHandle,
        new_ao: &str,
        has_audio_track: bool,
        is_playing: bool,
    ) -> Option<AudioDeviceChangeEvent> {
        let previous_ao = std::mem::replace(&mut self.current_ao, new_ao.to_string());

        // Check if audio sink failed or died while playing audio
        if (new_ao == "null" || new_ao.is_empty()) && has_audio_track && is_playing {
            let mut state = self.hotplug.lock().unwrap();
            let now = Instant::now();
            let is_burst = state
                .last_retry_instant
                .map(|t| now.duration_since(t).as_secs() < 5)
                .unwrap_or(false);

            if is_burst && state.retry_count >= 3 {
                log::error!(
                    "Audio sink failed persistently ({previous_ao} -> {new_ao}). Recovery retries exhausted."
                );
                state.recovery_status = AudioRecoveryStatus::Degraded {
                    reason:
                        "Audio sink failed persistently. Automatic retries halted to prevent loops."
                            .to_string(),
                };
                state
                    .pending_notifications
                    .push("Audio output sink failed. Automatic recovery paused.".to_string());
                return None;
            }

            state.retry_count += 1;
            state.last_retry_instant = Some(now);

            log::warn!(
                "Audio sink dropped or failed ({previous_ao} -> {new_ao}). Attempting recovery #{}/3 to 'auto'",
                state.retry_count
            );

            let _ = EqualizerManager::set_audio_device(handle, "auto");
            let _ = handle.command(&["ao-reload"]);

            let note = format!(
                "Audio output sink recovered (attempt #{}/3)",
                state.retry_count
            );
            state.pending_notifications.push(note);

            return Some(AudioDeviceChangeEvent::SinkFailed {
                previous_ao,
                fallback_ao: "auto".to_string(),
            });
        }

        None
    }

    /// Periodic maintenance hook called during event polling.
    pub fn poll_recovery(&self, _handle: &MpvHandle) {
        let mut state = self.hotplug.lock().unwrap();
        if let Some(t) = state.last_retry_instant {
            if t.elapsed().as_secs() > 10 && state.retry_count > 0 {
                state.retry_count = 0;
                if matches!(state.recovery_status, AudioRecoveryStatus::Degraded { .. }) {
                    state.recovery_status = AudioRecoveryStatus::Normal;
                }
            }
        }
    }

    /// Drains any pending user notification message.
    pub fn take_notification(&self) -> Option<String> {
        let mut state = self.hotplug.lock().unwrap();
        if state.pending_notifications.is_empty() {
            None
        } else {
            Some(state.pending_notifications.remove(0))
        }
    }

    // Internal property update hooks
    pub fn on_volume_changed(&mut self, volume: f64) {
        self.volume = volume;
    }

    pub fn on_mute_changed(&mut self, muted: bool) {
        self.is_muted = muted;
    }

    pub fn on_speed_changed(&mut self, speed: f64) {
        self.speed = speed;
    }

    pub fn on_codec_changed(&mut self, codec: String) {
        self.audio_codec = codec;
    }
}
